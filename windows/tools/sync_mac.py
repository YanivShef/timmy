"""Regenerate windows/timmy/engine/_mac/ from mac/ (the Mac app stays the single source of truth).

    python tools/sync_mac.py           write the files
    python tools/sync_mac.py --check   exit 1 (and list the files) if the committed copy differs from what mac/ gives

What is generated (DESIGN.md section 10):
  live_shared.py      selected top-level nodes of mac/live.py, copied verbatim (prompts, hallucination filters,
                      echo helpers, timestamps). mac/live.py is a script, so it cannot be imported; this module can.
                      The config-derived globals (OWNER, CUSTOM, models...) are wrapped verbatim in configure(cfg).
  pdf.py, skill_render.py, pdf_template.html, pdf_sample.md
                      copied verbatim, then the exact string patches in PATCHES (each must match the declared
                      number of times, otherwise the tool fails, so a Mac change can never silently skip a patch).

Never edit files in _mac/ by hand: change mac/ (or the patch list here) and re-run this tool.
"""
import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAC = ROOT / "mac"
OUT = ROOT / "windows" / "timmy" / "engine" / "_mac"

