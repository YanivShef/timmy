class SyncError(Exception):
    pass


def _names(node):
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
        return {node.name}
    if isinstance(node, ast.Assign):
        out = set()
        for t in node.targets:
            for n in ast.walk(t):
                if isinstance(n, ast.Name):
                    out.add(n.id)
        return out
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return {node.target.id}
    return set()


def build_live_shared(src: str) -> str:
    tree = ast.parse(src)
    lines = src.splitlines()
    want, want_cfg = set(LIVE_NAMES), set(LIVE_CONFIG_NAMES)
    found, found_cfg = set(), set()
    body, cfg_body = [], []
    seen_ranges = set()

    def seg(node):
        start = node.lineno
        if getattr(node, "decorator_list", None):
            start = min(d.lineno for d in node.decorator_list)
        return start, node.end_lineno

    for node in tree.body:
        names = _names(node)
        rng = seg(node)
        if names & want:
            found |= names & want
            if rng not in seen_ranges:
                seen_ranges.add(rng)
                body.append("\n".join(lines[rng[0] - 1:rng[1]]))
        elif names & want_cfg or (isinstance(node, ast.If) and ast.unparse(node.test) in LIVE_CONFIG_IFS):
            found_cfg |= names & want_cfg
            if rng not in seen_ranges:
                seen_ranges.add(rng)
                cfg_body.append("\n".join(lines[rng[0] - 1:rng[1]]))
    missing = (want - found) | (want_cfg - found_cfg)
    if missing:
        raise SyncError(f"mac/live.py no longer defines: {sorted(missing)} (update LIVE_NAMES in tools/sync_mac.py)")
    for chunk in cfg_body:
        if '"""' in chunk or "'''" in chunk:
            raise SyncError("a config statement contains a multi-line string; it cannot be indented into configure()")
    indented = "\n".join("    " + ln if ln.strip() else "" for chunk in cfg_body for ln in chunk.splitlines())
    glob = ", ".join(n for n in LIVE_CONFIG_NAMES)
    out = LIVE_HEADER + "\n\n" + "\n".join(body) + "\n" + LIVE_CONFIGURE.format(globals=glob, body=indented)
    ast.parse(out)   # must stay valid Python
    return out


def apply_patches(name: str, text: str) -> str:
    for old, new, count in PATCHES[name]:
        n = text.count(old)
        if n != count:
            raise SyncError(f"{name}: patch expected {count} match(es), found {n}: {old[:70]!r}")
        text = text.replace(old, new)
    return text


def generate() -> dict[str, str]:
    """All generated files: {file name: content}. Pure (reads mac/, writes nothing)."""
    files = {"__init__.py": INIT}
    files["live_shared.py"] = build_live_shared((MAC / "live.py").read_text(encoding="utf-8"))
    for name in PATCHES:
        text = (MAC / name).read_text(encoding="utf-8")
        out = apply_patches(name, text)
        if name.endswith(".py"):
            out = f"# GENERATED by windows/tools/sync_mac.py from mac/{name} (+ Windows patches). Do not edit.\n" + out
            ast.parse(out)
        files[name] = out
    return files


def diff(files: dict[str, str]) -> list[str]:
    bad = []
    for name, content in files.items():
        p = OUT / name
        # text compare with universal newlines: a Windows checkout (core.autocrlf=true on CI runners) has CRLF files
        if not p.exists() or p.read_text(encoding="utf-8") != content:
            bad.append(name)
    for p in OUT.glob("*"):
        if p.is_file() and p.name not in files:
            bad.append(f"{p.name} (stale, not generated)")
    return bad


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only compare, write nothing")
    a = ap.parse_args(argv)
    try:
        files = generate()
    except SyncError as e:
        print(f"sync_mac: {e}", file=sys.stderr)
        return 2
    if a.check:
        bad = diff(files)
        if bad:
            print("timmy/engine/_mac is out of date with mac/: " + ", ".join(bad) + ". Run: python tools/sync_mac.py", file=sys.stderr)
            return 1
        print("timmy/engine/_mac is in sync with mac/")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (OUT / name).write_bytes(content.encode("utf-8"))   # LF line endings on every OS (the drift test ignores CRLF)
    for p in OUT.glob("*"):
        if p.is_file() and p.name not in files:
            p.unlink()
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
